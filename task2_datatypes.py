"""
Task 2: Variables & Data Types
Declares variables of different data types (Integer, Float, String, Boolean)
and prints each variable along with its data type using type().
"""

age = 20                    
height = 5.9                
student_name = "Hrithik"     
is_student = True           

print("Variable Values and Their Data Types")
print("-----------------------------------------------")
print(f"age = {age} -> type: {type(age)}")
print(f"height = {height} -> type: {type(height)}")
print(f"student_name = '{student_name}'  -> type: {type(student_name)}")
print(f"is_student = {is_student}  -> type: {type(is_student)}")
